/// Planned operating mode for the on-device app (later milestones).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    Keyboard,
    Mouse,
    Combo,
}

impl Mode {
    pub const ALL: [Self; 3] = [Self::Keyboard, Self::Mouse, Self::Combo];

    pub fn label(self) -> &'static str {
        match self {
            Self::Keyboard => "keyboard",
            Self::Mouse => "mouse",
            Self::Combo => "keyboard+mouse",
        }
    }

    pub fn next(self) -> Self {
        match self {
            Self::Keyboard => Self::Mouse,
            Self::Mouse => Self::Combo,
            Self::Combo => Self::Keyboard,
        }
    }
}

/// Gadget is up when both HID endpoints exist (set by the daemon after bind).
pub fn can_emit_reports() -> bool {
    std::path::Path::new("/dev/hidg0").exists() && std::path::Path::new("/dev/hidg1").exists()
}

#[cfg(test)]
mod tests {
    use super::*;

    const JIGGLER_KEYBOARD: [u8; 63] = [
        0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, 0x05, 0x07, 0x19, 0xe0, 0x29, 0xe7, 0x15, 0x00, 0x25,
        0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02, 0x95, 0x01, 0x75, 0x08, 0x81, 0x03, 0x95, 0x05,
        0x75, 0x01, 0x05, 0x08, 0x19, 0x01, 0x29, 0x05, 0x91, 0x02, 0x95, 0x01, 0x75, 0x03, 0x91,
        0x03, 0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65, 0x05, 0x07, 0x19, 0x00, 0x29, 0x65,
        0x81, 0x00, 0xc0,
    ];

    const JIGGLER_MOUSE: [u8; 52] = [
        0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0x09, 0x01, 0xa1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29,
        0x03, 0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05,
        0x81, 0x03, 0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7f, 0x75,
        0x08, 0x95, 0x03, 0x81, 0x06, 0xc0, 0xc0,
    ];

    #[test]
    fn keyboard_descriptor_matches_jiggler_reference() {
        assert_eq!(BOOT_KEYBOARD_REPORT_DESC, JIGGLER_KEYBOARD);
    }

    #[test]
    fn mouse_descriptor_matches_jiggler_reference() {
        assert_eq!(BOOT_MOUSE_REPORT_DESC, JIGGLER_MOUSE);
    }

    #[test]
    fn boot_report_lengths_match_jiggler() {
        assert_eq!(KEYBOARD_REPORT_LEN, 8);
        assert_eq!(MOUSE_REPORT_LEN, 4);
    }

    #[test]
    fn mode_cycles_through_all_variants() {
        let mut m = Mode::Keyboard;
        m = m.next();
        assert_eq!(m, Mode::Mouse);
        m = m.next();
        assert_eq!(m, Mode::Combo);
        m = m.next();
        assert_eq!(m, Mode::Keyboard);
    }
}