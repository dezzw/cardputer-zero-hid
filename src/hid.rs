/// 4-byte boot mouse reports: `[buttons, dx, dy, wheel]`.
pub const MOUSE_REPORT_LEN: u8 = 4;

/// USB HID interface protocol: keyboard (boot).
pub const KEYBOARD_PROTOCOL: u8 = 1;

/// USB HID interface protocol: mouse (boot).
pub const MOUSE_PROTOCOL: u8 = 2;

/// Boot interface subclass.
pub const BOOT_SUBCLASS: u8 = 1;

